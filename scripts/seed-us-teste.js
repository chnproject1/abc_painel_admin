/**
 * Popula a tabela PedidoUs com pedidos de teste cobrindo todos os planos e
 * todos os estados do funil, para conferir o portal admin US.
 *
 *   node scripts/seed-us-teste.js
 *
 * Todos os IDs começam com "cs_test_" e são removíveis com:
 *   node scripts/limpar-us-teste.js
 *
 * O script usa upsert, então rodar duas vezes não duplica nada.
 *
 * ATENÇÃO: escreve no banco apontado por DATABASE_URL. Confira o .env antes.
 */
require("dotenv").config();
const { PrismaClient } = require("@prisma/client");

const prisma = new PrismaClient();

// Preços da operação US, em USD
const PRECO = { basic: 14, silver: 19, up1: 12, up2: 9, ds: 12 };

const ESTILOS = ["Pop Ballad", "Country", "R&B", "Acoustic Folk", "Gospel", "Rock"];

/**
 * Monta um pedido consistente com as regras do funil:
 *   - a página Premium (link_pagina*) só existe se up1 ou ds foram pagos
 *   - os slots 2 e 3 só existem se up2 foi pago
 *   - o downsell só é ofertado quando up1 e up2 foram recusados
 */
function montar({
  n,                    // número do teste, vira o id
  nome,
  plano,
  status = "pago",
  up1 = null,
  up2 = null,
  ds = null,
  gerouMusica = true,
  erroGeracao = false,
  entregue = true,
  upGerouMusica = true,
  upErroGeracao = false,
  upEntregue = true,
  diasAtras = 0,
}) {
  const id = `cs_test_${String(n).padStart(3, "0")}`;
  const agora = Date.now();
  const dataPedido = new Date(agora - diasAtras * 24 * 60 * 60 * 1000);
  const tier = plano.startsWith("silver") ? "silver" : "basic";

  const temExtras = up2 === "pago";
  const pagou = status === "pago";

  // A automação gera a página Premium de toda música, independente de o cliente
  // ter comprado up1/ds. O que up1 e ds decidem é só se o link é ENTREGUE no envio.
  const slug = nome.toLowerCase().replace(/[^a-z]+/g, "-");
  const musica = (i) => ({
    song_id:     gerouMusica ? `sng_test_${n}_${i}` : null,
    link_audio:  gerouMusica ? `https://cdn.example.com/test/${slug}-${i}.mp3` : null,
    link_basica: gerouMusica ? `https://abcmusic.example.com/b/${slug}-${i}` : null,
    link_pagina: gerouMusica ? `https://abcmusic.example.com/p/${slug}-${i}` : null,
  });

  const m1 = musica(1);
  const m2 = temExtras && upGerouMusica ? musica(2) : {};
  const m3 = temExtras && upGerouMusica ? musica(3) : {};

  return {
    id,
    nome,
    email:      `${slug}@example.com`,
    nomefiscal: nome,
    zip_code:   String(10001 + n * 137).slice(0, 5),
    plano,
    idioma:     "en",

    status,
    up1_status: up1,
    up2_status: up2,
    ds_status:  ds,

    estilo: ESTILOS[n % ESTILOS.length],
    letra:  `[Verse 1]\nThis is a test lyric for ${nome}\nGenerated by seed-us-teste.js\n\n[Chorus]\nOnly test data, nothing real`,

    // Entrega principal
    gerou_musica: pagou && gerouMusica,
    erro_geracao: erroGeracao,
    song_id:      m1.song_id,
    link_audio:   m1.link_audio,
    link_basica:  m1.link_basica,
    link_pagina:  m1.link_pagina,
    link_mp4:     null,
    data_entrega: pagou && gerouMusica && entregue ? new Date(dataPedido.getTime() + 36e5) : null,
    entrega_email: pagou && gerouMusica && entregue,
    tentativa_geracao: erroGeracao ? 2 : 1,
    tentativa_envio:   entregue ? 1 : 0,

    // Entrega do upsell 2
    up_gerou_musica: temExtras && upGerouMusica,
    up_erro_geracao: temExtras && upErroGeracao,
    song_id2:     m2.song_id     ?? null,
    link_audio2:  m2.link_audio  ?? null,
    link_basica2: m2.link_basica ?? null,
    link_pagina2: m2.link_pagina ?? null,
    song_id3:     m3.song_id     ?? null,
    link_audio3:  m3.link_audio  ?? null,
    link_basica3: m3.link_basica ?? null,
    link_pagina3: m3.link_pagina ?? null,
    up_data_entrega: temExtras && upGerouMusica && upEntregue ? new Date(dataPedido.getTime() + 72e5) : null,
    up_entrega_email: temExtras && upGerouMusica && upEntregue,
    up_tentativa_geracao: temExtras ? (upErroGeracao ? 2 : 1) : 0,
    up_tentativa_envio:   temExtras && upEntregue ? 1 : 0,

    funil:       "us_main",
    recovery_id: null,
    recuperacao: 0,

    data_pedido: dataPedido,
    valor:     pagou ? PRECO[tier] : null,
    up1_valor: up1 === "pago" ? PRECO.up1 : null,
    up2_valor: up2 === "pago" ? PRECO.up2 : null,
    ds_valor:  ds  === "pago" ? PRECO.ds  : null,

    utm_source:   n % 2 === 0 ? "facebook" : "tiktok",
    utm_campaign: `us_launch_${tier}`,
    utm_medium:   "paid_social",
    utm_content:  `creative_${n}`,
    utm_term:     null,
    utm_id:       `camp_${1000 + n}`,
    fbclid:       n % 2 === 0 ? `fb.1.test.${n}` : null,
    ttclid:       n % 2 === 1 ? `tt.1.test.${n}` : null,
    pixel_id:     n % 2 === 0 ? "111111111111111" : "222222222222222",
    ip:           `203.0.113.${10 + n}`,
  };
}

