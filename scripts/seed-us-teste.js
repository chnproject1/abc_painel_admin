(async () => {
  const url = process.env.DATABASE_URL || "";
  const host = url.replace(/^.*@/, "").replace(/\/.*$/, "");
  console.log(`Banco: ${host}`);

  let criados = 0;
  for (const caso of CASOS) {
    const dados = montar(caso);
    await prisma.pedidoUs.upsert({
      where:  { id: dados.id },
      create: dados,
      update: dados,
    });
    criados++;
    console.log(`  ${dados.id}  ${dados.plano.padEnd(15)} ${dados.nome}`);
  }

  const total = await prisma.pedidoUs.count();
  console.log(`\n${criados} pedidos de teste gravados. Total na tabela PedidoUs: ${total}`);
  console.log("Para remover: node scripts/limpar-us-teste.js");

  await prisma.$disconnect();
})().catch(async (e) => {
  console.error("Erro:", e.message);
  await prisma.$disconnect();
  process.exit(1);
});
